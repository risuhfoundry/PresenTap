import * as React from "react";

import { cn } from "@/lib/utils";

/**
 * Card — white surface, 12px radius, 24px padding, subtle shadow (Design.md §6.4).
 * Composed of Card / CardHeader / CardTitle / CardDescription / CardContent /
 * CardFooter. No business logic — presentational only.
 */
export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border border-border bg-white shadow-card",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

